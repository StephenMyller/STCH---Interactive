#!/usr/bin/env python3
r"""Resolve \proofref in Lwarp MathJax proof trees from LaTeX's .aux data.

Run after `lwarpmk html` and before copying generated HTML to the site.
References not found in main_html.aux cause a build failure, never '???'.
"""

from pathlib import Path
import os
import re
import sys

AUX = Path('main_html.aux')
TREE = re.compile(r'(\\begin\s*\{prooftree\})(.*?)(\\end\s*\{prooftree\})', re.S)
PROOFREF = re.compile(r'\\proofref\s*\{\s*([^{}\s]+)\s*\}')
NEWLABEL = re.compile(r'^\\newlabel\{([^{}]+)\}')
SAFE_URL = re.compile(r'^[A-Za-z0-9_.:/-]+$')


def group(text, start):
    """Read a balanced {...} group, supporting nested LaTeX braces."""
    if start >= len(text) or text[start] != '{':
        raise ValueError('Expected opening brace in LaTeX aux data')
    level = 0
    for i in range(start, len(text)):
        if text[i] == '{' and (i == 0 or text[i - 1] != '\\'):
            level += 1
        elif text[i] == '}' and (i == 0 or text[i - 1] != '\\'):
            level -= 1
            if level == 0:
                return text[start + 1:i], i + 1
    raise ValueError('Unbalanced braces in LaTeX aux data')


def fields(text):
    result = []
    i = 0
    while i < len(text):
        if text[i].isspace():
            i += 1
            continue
        value, i = group(text, i)
        result.append(value)
    return result


def references(aux_text):
    labels, pages = {}, {}
    for line in aux_text.splitlines():
        m = NEWLABEL.match(line)
        if not m:
            continue
        name = m.group(1)
        outer, _ = group(line, m.end())
        values = fields(outer)
        if name.endswith('@lwarp'):
            if len(values) >= 3:
                pages[name[:-6]] = values[2]
        elif not name.endswith(('@cref', '@lwarp@image')) and values:
            labels[name] = values[0]
    return labels, pages


def main():
    html_paths = list(Path('.').glob('*.html'))
    # HTML may come from a build cache already processed on a previous run.
    if not any(PROOFREF.search(p.read_text(encoding='utf-8')) for p in html_paths):
        print('proofref: no unresolved proof references in HTML')
        return

    if not AUX.exists():
        raise RuntimeError(
            'main_html.aux is missing. Rebuild Lwarp HTML (or include the aux '
            'file in the build cache) before resolving proof references.'
        )
    labels, pages = references(AUX.read_text(encoding='utf-8'))
    replacements = 0

    for path in html_paths:
        source = path.read_text(encoding='utf-8')

        def replace_tree(tree_match):
            nonlocal replacements

            def replace_ref(ref_match):
                nonlocal replacements
                key = ref_match.group(1)
                if key not in labels or not labels[key] or key not in pages or not pages[key]:
                    raise RuntimeError(f'Unresolved proof reference {key!r} in {path}')
                page = pages[key]
                if not SAFE_URL.fullmatch(page) or not SAFE_URL.fullmatch(key):
                    raise RuntimeError(f'Unsafe/unexpected URL from reference {key!r}: {page!r}')
                replacements += 1
                number = labels[key]
                # \href is supported by MathJax and yields a real clickable link.
                return rf'\href{{{page}.html#{key}}}{{{number}}}'

            return tree_match.group(1) + PROOFREF.sub(replace_ref, tree_match.group(2)) + tree_match.group(3)

        output = TREE.sub(replace_tree, source)
        # Don't silently leave an unsupported use elsewhere in the page.
        if PROOFREF.search(output):
            raise RuntimeError(f'Unprocessed \\proofref outside a prooftree in {path}')
        if output != source:
            temp = path.with_name(path.name + '.proofref-tmp')
            temp.write_text(output, encoding='utf-8')
            os.replace(temp, path)  # Works for root-owned HTML generated by TeX Live Docker.

    print(f'proofref: resolved {replacements} reference(s) in Gentzen trees')


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print(f'proofref: ERROR: {error}', file=sys.stderr)
        sys.exit(1)
